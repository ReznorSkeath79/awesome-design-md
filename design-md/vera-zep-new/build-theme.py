#!/usr/bin/env python3
"""Regenerate theme.css from a Zephium checkout's real sources.

    python3 build-theme.py ~/Work/ZepBrowser

Everything in theme.css is Zephium's own CSS, copied verbatim, with three
mechanical changes so it runs outside the Svelte/Tailwind build:
  1. Tailwind's `@theme static { ... }` block becomes `:root { ... }`.
  2. Svelte's `:global(x)` wrappers are unwrapped to `x` (component styles are
     unscoped here, so their class names are global).
  3. A short "web app defaults" block at the end picks the light theme and the
     window ground the live app shows over Liquid Glass.
"""
import re
import subprocess
import sys
from pathlib import Path

repo = Path(sys.argv[1] if len(sys.argv) > 1 else "~/Work/ZepBrowser").expanduser()
src = repo / "frame" / "src"
out = Path(__file__).with_name("theme.css")

TOKENS = [
    "styles/tokens/primitive.css",
    "styles/tokens/avatar.css",
    "styles/tokens/sky.css",
    "styles/tokens.css",
    "styles/axes/palette.css",
    "styles/axes/tint.css",
    "styles/axes/density.css",
    "styles/axes/contrast.css",
    "styles/axes/material.css",
    "styles/axes/motion.css",
    "styles/axes/type.css",
]
BASE = ["styles/controls.css", "styles/favicon.css", "styles/browser.css"]
SHARED_CSS = sorted(str(p.relative_to(src)) for p in (src / "shared/ui").rglob("*.css"))
COMPONENTS = sorted(str(p.relative_to(src)) for p in (src / "shared/ui").rglob("*.svelte")) + [
    "features/tabs/components/TabRow.svelte",
    "features/tabs/components/TabList.svelte",
    "features/tabs/components/SpaceBar.svelte",
    "features/address/components/AddressField.svelte",
    "features/dock/components/Dock.svelte",
    "features/sidebar/components/Sidebar.svelte",
    "features/sidebar/components/SidebarHeader.svelte",
    "features/sidebar/components/ModeTabs.svelte",
]


def unglobal(css: str) -> str:
    # :global(.a .b) -> .a .b, with any depth of nested parentheses inside.
    out, i = [], 0
    while (start := css.find(":global(", i)) != -1:
        out.append(css[i:start])
        depth, j = 1, start + len(":global(")
        while depth:
            depth += {"(": 1, ")": -1}.get(css[j], 0)
            j += 1
        out.append(css[start + len(":global(") : j - 1].strip())
        i = j
    out.append(css[i:])
    return "".join(out)


def svelte_style(path: Path) -> str:
    text = path.read_text()
    blocks = re.findall(r"<style[^>]*>(.*?)</style>", text, re.S)
    return unglobal("\n".join(blocks)).strip()


def section(title: str) -> str:
    return f"\n\n/* {'=' * 74}\n   {title}\n   {'=' * 74} */\n"


commit = subprocess.run(
    ["git", "-C", str(repo), "rev-parse", "--short", "HEAD"], capture_output=True, text=True
).stdout.strip()

parts = [
    "/* Vera Zep New — Zephium's real design system, for web apps.\n"
    f"   Generated by build-theme.py from ReznorSkeath79/Zephium @ {commit}. Do not hand-edit:\n"
    "   change Zephium (or the defaults block at the end) and regenerate.\n"
    '   Use: <html data-theme="light" data-material="liquid_glass"> — see DESIGN.md. */'
]

parts.append(section("1. Tokens and axes (frame/src/styles)"))
for rel in TOKENS:
    css = (src / rel).read_text()
    css = css.replace("@theme static {", ":root {")
    css = re.sub(r"^\s*/\* stylelint-disable-next-line[^*]*\*/\n", "", css, flags=re.M)
    css = re.sub(r"^\s*--radius-\*: initial;\n", "", css, flags=re.M)
    parts.append(f"\n/* --- {rel} --- */\n{css}")

parts.append(section("2. Base: controls, favicons, browser chrome (frame/src/styles)"))
for rel in BASE:
    css = (src / rel).read_text()
    css = "\n".join(l for l in css.splitlines() if not l.startswith(("@import", "@source")))
    parts.append(f"\n/* --- {rel} --- */\n{unglobal(css)}")

parts.append(section("3. Shared UI materials (frame/src/shared/ui/**/*.css)"))
for rel in SHARED_CSS:
    parts.append(f"\n/* --- {rel} --- */\n{(src / rel).read_text()}")

parts.append(section("4. Component styles (Svelte <style> blocks, unscoped)"))
for rel in COMPONENTS:
    css = svelte_style(src / rel)
    if css:
        parts.append(f"\n/* --- {rel} --- */\n{css}")

parts.append(section("5. Web app defaults (the only part not copied from Zephium)"))
parts.append(
    """
/* The live window over Liquid Glass reads as this grey; the sidebar's lifts
   (white at 30%) are tuned against it. Override --vzn-window-ground per app. */
:root {
  --vzn-window-ground: #878787;
}
:root:not([data-material="none"])[data-material] body {
  background: var(--vzn-window-ground);
}
html,
body {
  height: 100%;
  margin: 0;
}
"""
)

out.write_text("\n".join(parts) + "\n")
print(f"wrote {out} ({out.stat().st_size // 1024} KB) from {commit}")
